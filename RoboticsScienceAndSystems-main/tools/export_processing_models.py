"""Generate Processing's Java model tables from the deployed C++ headers."""
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(*, ablation_dir=None):
    source = ROOT / "StampC3_Template"
    tree1 = (source / "tree1_model.hpp").read_text(encoding="utf-8")
    tree2 = (source / "Tree2Model.h").read_text(encoding="utf-8")
    measured = (source / "Tree2MeasuredModel.h").read_text(encoding="utf-8")
    policy = (source / "Tree2ControlPolicy.h").read_text(encoding="utf-8")
    leaves = re.findall(r"^    \{([^,]+f), ([^,]+f), ([^}]+f)\},$", measured, re.MULTILINE)
    if len(leaves) < 2:
        raise ValueError("Unrecognized measured Tree2 export")
    # In the isolated test class, hold reverse at the legacy policy. With the
    # legacy switch on, replace only its forward regression by the raw CART.
    dispatch = "    if(LEGACY) return legacyDifference(angle,signal,prevL,prevR);\n"
    if ablation_dir is not None:
        dispatch = """    if(signal<0) return legacyDifference(angle,signal,prevL,prevR);
    if(LEGACY) {
      int leaf=0;
      while(leaf<UPPER.length-1 && angle>UPPER[leaf]) leaf++;
      return PWM[leaf];
    }
"""
    steering = dict(re.findall(r"constexpr float (\w+) = ([^;]+);", policy))
    config = (source / "tree1_config.hpp").read_text(encoding="utf-8")
    nodes = re.findall(r"\{(-?\d+), ([^,]+), (-?\d+), (-?\d+), (-?\d+), \{\{([^}]+)\}\}\}", tree1)
    if not nodes:
        raise ValueError("Unrecognized Tree1 export")
    constants = dict(re.findall(r"(?:double|int) (\w+) = ([^;]+);", config))
    raw = tree2.split("inline float rawPredict(", 1)[1].split("inline float predict(", 1)[0]
    raw = raw[raw.index("  if (double(x["):].strip()
    raw = re.sub(r"double\((x\[\d+\])\)", r"(double)(\1)", raw)
    rows = ",\n".join("    {" + ",".join(n[:5]) + "," + n[5] + "}" for n in nodes)
    hashes = "\n".join("// " + name + " SHA256 " + hashlib.sha256((source/name).read_bytes()).hexdigest()
                       for name in ("tree1_model.hpp", "tree1_config.hpp", "Tree2Model.h",
                                    "Tree2MeasuredModel.h", "Tree2ControlPolicy.h"))
    result = '''// Generated by tools/export_processing_models.py. Do not edit weights here.
''' + hashes + '''
public final class TreeModels {
  public static final int FORWARD=0, REVERSE=1, ROTATE=2, STOP=3;
  public static final double SPACING=''' + constants["sample_spacing"] + ''';
  public static final double LOOKAHEAD=''' + constants["lookahead_distance"] + ''';
  public static final double GOAL_TOLERANCE=''' + constants["goal_tolerance"] + ''';
  public static final int SEARCH_WINDOW=''' + constants["search_window"] + ''';
  private static final double[][] NODES = {
''' + rows + '''
  };
  private static void vote(int index, double[] x, double[] scores) {
    double[] n=NODES[index];
    if (n[0]<0) { for(int i=0;i<4;i++) scores[i]+=n[i+5]; return; }
    if (n[4]>=0) vote((int)n[4],x,scores);
    vote((int)(x[(int)n[0]]<=n[1]?n[2]:n[3]),x,scores);
  }
  public static int action(double[] x) {
    for(double v:x) if(!Double.isFinite(v)) return STOP;
    double[] scores=new double[4]; vote(0,x,scores);
    double total=0; for(double s:scores) total+=s;
    if(!(total>0)) return STOP;
    int best=3; for(int i=3;i>=0;i--) if(scores[i]>scores[best]) best=i;
    return best;
  }
  private static float rawPredict(float eCW,int signal,float previousDifference) {
    final float[] x={eCW,(float)signal,previousDifference};
    final float[] z={1.0f,x[0],x[1],x[2]/255.0f};
''' + raw + '''
  public static float legacyDifference(float eCW,int signal,int prevL,int prevR) {
    float d=(float)prevR-(float)prevL;
    return 0.5f*(rawPredict(eCW,signal,d)-rawPredict(-eCW,signal,-d));
  }
  private static final boolean LEGACY = Boolean.getBoolean("tree2.legacy");
  private static final float[] UPPER = {''' + ", ".join(u for u, _, _ in leaves) + '''};
  private static final float[] ANGLE = {''' + ", ".join(x for _, x, _ in leaves) + '''};
  private static final float[] PWM = {''' + ", ".join(y for _, _, y in leaves) + '''};
  private static float interpolate(float angle) {
    int lo=0, hi=ANGLE.length-1;
    if(angle<=ANGLE[lo]) return PWM[lo];
    if(angle>=ANGLE[hi]) return PWM[hi];
    while(lo<hi) {
      int mid=lo+(hi-lo)/2;
      if(angle>UPPER[mid]) lo=mid+1; else hi=mid;
    }
    if(angle<ANGLE[lo]) lo--;
    float a=ANGLE[lo], b=ANGLE[lo+1], p=PWM[lo], q=PWM[lo+1];
    if(a<0 && b>0) {
      if(angle<0) { b=0; q=0; } else { a=0; p=0; }
    }
    float t=(angle-a)/(b-a);
    return p+t*(q-p);
  }
  public static float difference(float angle,int signal,int prevL,int prevR) {
''' + dispatch + '''    float magnitude=Math.abs(angle), deadband=''' + steering["DEADBAND_RAD"] + ''';
    if(magnitude<=deadband) return 0;
    float sign=angle>0?-1f:1f, envelope=''' + steering["GAIN"] + '''*(magnitude-deadband);
    if(signal>0) return sign*Math.min(envelope,Math.max(0f,sign*interpolate(angle)));
    float target=Math.min(envelope,''' + steering["TEACHER_TARGET_LIMIT"] + ''');
    float history=Math.min(target,Math.max(0f,sign*(prevR-prevL)));
    return sign*(target+''' + steering["REVERSE_HISTORY_WEIGHT"] + '''*(history-target));
  }
  public static float forwardSpeedScale(float angle,float difference) {
    if(LEGACY) return 1f;
    float nominal=Math.min(''' + steering["GAIN"] + '''*(Math.abs(angle)-''' + steering["DEADBAND_RAD"] + '''),''' + steering["TEACHER_TARGET_LIMIT"] + ''');
    float actual=Math.abs(difference);
    return actual<nominal?actual/nominal:1f;
  }
}
'''
    target = (ROOT / "DigitalTwin" if ablation_dir is None else ablation_dir) / "TreeModels.java"
    target.write_text(result, encoding="utf-8")
    print(f"Generated {target} ({len(nodes)} Tree1 nodes)")


if __name__ == "__main__":
    generate()
