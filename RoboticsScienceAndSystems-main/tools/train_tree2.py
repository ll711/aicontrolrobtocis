"""Fit a forward PWM CART, select on held-out acquisitions and export the measured controller."""
import argparse
import json
import platform
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.tree import DecisionTreeRegressor

from tree2_data import DATA, MODEL, ROOT, load_experiments
from export_processing_models import generate as export_processing


VERSION = "measured-forward-v1"
DEADBAND = np.float32(np.deg2rad(.36))
GAIN = np.float32(90)


def angle_input(rows):
    return np.deg2rad(rows.error_deg.to_numpy()).astype(np.float32)


def metrics(y, p):
    y, p = np.asarray(y, dtype=float), np.asarray(p, dtype=float)
    error = p - y
    return dict(n=len(y), mae=float(np.abs(error).mean()), rmse=float(np.sqrt(np.mean(error**2))),
                wrong_sign=int((y*p < 0).sum()), wrong_sign_rate=float((y*p < 0).mean()),
                zero=int((p == 0).sum()), sign_mismatch_rate=float((np.sign(p) != np.sign(y)).mean()))


def extract_leaves(estimator, x):
    tree = estimator.tree_
    ids = estimator.apply(x[:, None])
    leaves = []

    def visit(node, upper):
        if tree.children_left[node] == -1:
            samples = x[ids == node]
            leaves.append(dict(upper_rad=upper, center_rad=float(np.float32(samples.mean(dtype=float))),
                               pwm=float(np.float32(tree.value[node].item())), samples=len(samples)))
        else:
            visit(tree.children_left[node], float(tree.threshold[node]))
            visit(tree.children_right[node], upper)

    visit(0, None)
    return leaves


def knots(leaves):
    # A zero-error equilibrium separates the two independently learned motor directions.
    points = [(r["center_rad"], r["pwm"]) for r in leaves] + [(0., 0.)]
    return np.asarray(sorted(points), dtype=np.float32).T


def measured_prediction(angle, leaves):
    x, y = knots(leaves)
    curve = np.interp(angle, x, y)
    sign = -np.sign(angle)
    limit = GAIN * np.maximum(np.abs(angle) - DEADBAND, 0.)
    return sign * np.clip(sign*curve, 0., limit)


def raw_prediction(angle, leaves):
    upper = [r["upper_rad"] for r in leaves[:-1]]
    values = np.array([r["pwm"] for r in leaves])
    return values[np.searchsorted(upper, np.asarray(angle, dtype=np.float32).astype(float))]


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, allow_nan=False) + "\n",
                    encoding="utf-8", newline="\n")


def cpp_float(value):
    literal = format(float(value), ".9g")
    if "." not in literal and "e" not in literal:
        literal += ".0"
    return literal + "f"


def export_header(leaves):
    rows = []
    for leaf in leaves:
        threshold = leaf["upper_rad"]
        upper = np.finfo(np.float32).max if threshold is None else np.float32(threshold)
        # CART compares a float32 input to a double midpoint with <=. Rounding the
        # midpoint up would move one representable input into the wrong leaf.
        if threshold is not None and float(upper) > threshold:
            upper = np.nextafter(upper, np.float32(-np.inf))
        fields = [cpp_float(v) for v in (upper, leaf["center_rad"], leaf["pwm"])]
        rows.append("    {" + ", ".join(fields) + "},")
    header = ["#pragma once", "// Generated by tools/train_tree2.py from grouped forward TURN records.",
              f"// Version: {VERSION}. Angle: clockwise radians. Output: right minus left PWM.",
              "namespace tree2_measured {", "struct Leaf { float upper; float center; float difference; };",
              "inline constexpr Leaf LEAVES[] = {", *rows, "};", "}  // namespace tree2_measured", ""]
    (ROOT / "StampC3_Template/Tree2MeasuredModel.h").write_text("\n".join(header), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DATA)
    args = parser.parse_args()
    rows, audit = load_experiments(args.data)
    train = rows[rows.split.eq("train")]
    valid = rows[rows.split.eq("validation")]
    x, v = angle_input(train), angle_input(valid)
    y, w = train.pwm_right_minus_left.to_numpy(), valid.pwm_right_minus_left.to_numpy()
    candidates = []
    fitted = {}
    for depth in (4, 6, 8):
        for minimum in (32, 128, 512):
            reg = DecisionTreeRegressor(max_depth=depth, min_samples_leaf=minimum, random_state=42)
            reg.fit(x[:, None], y)
            leaves = extract_leaves(reg, x)
            np.testing.assert_allclose(raw_prediction(v, leaves), reg.predict(v[:, None]), atol=2e-6, rtol=0)
            candidates.append(dict(depth=depth, minimum=minimum, leaves=len(leaves),
                                   train_raw=metrics(y, reg.predict(x[:, None])),
                                   validation_raw=metrics(w, reg.predict(v[:, None])),
                                   validation_deployed=metrics(w, measured_prediction(v, leaves))))
            fitted[depth, minimum] = leaves
    # Select a compact table within 1% of the lowest deployed validation MAE.
    best = min(c["validation_deployed"]["mae"] for c in candidates)
    eligible = [c for c in candidates if c["validation_deployed"]["mae"] <= 1.01*best]
    chosen = min(eligible, key=lambda c: (c["leaves"], c["validation_deployed"]["mae"], c["depth"]))
    leaves = fitted[chosen["depth"], chosen["minimum"]]
    model = dict(version=VERSION, feature="shortest_clockwise_remaining_angle_rad",
                 target="right_pwm - left_pwm", domain="forward TURN", split="entire acquisition by target",
                 selected=dict(depth=chosen["depth"], min_samples_leaf=chosen["minimum"]),
                 leaves=leaves, deadband_rad=float(DEADBAND), envelope_pwm_per_rad=float(GAIN))
    write_json(MODEL, model)
    write_json(ROOT / "docs/tree2_training.json",
               dict(version=VERSION, python=platform.python_version(), numpy=np.__version__,
                    pandas=pd.__version__, sklearn=sklearn.__version__, audit=audit, candidates=candidates,
                    selected=model["selected"]))
    export_header(leaves)
    export_processing()
    print(f"{VERSION}: depth {chosen['depth']}, min leaf {chosen['minimum']}, {len(leaves)} leaves")
    for c in candidates:
        print(c["depth"], c["minimum"], c["leaves"], "val MAE raw/deployed",
              round(c["validation_raw"]["mae"], 4), round(c["validation_deployed"]["mae"], 4))


if __name__ == "__main__":
    main()
